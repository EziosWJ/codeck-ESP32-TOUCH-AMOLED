# Generate the small LVGL 4 bpp font used by the home face on Windows.
# Characters used by live quota labels, periods and countdowns.
Add-Type -AssemblyName System.Drawing
# Code points keep this script independent of Windows PowerShell's script encoding.
$characters = @(0x0020, 0x002d, 0x0030, 0x0031, 0x0032, 0x0033, 0x0034, 0x0035,
    0x0036, 0x0037, 0x0038, 0x0039, 0x003a, 0x0048, 0x004d, 0x5206, 0x5c0f, 0x5ea6, 0x65f6, 0x6709,
    0x7f6e, 0x8fd8, 0x91cd, 0x989d) | ForEach-Object { [char]$_ }
$font = [System.Drawing.Font]::new('Microsoft YaHei', 20, [System.Drawing.FontStyle]::Regular,
    [System.Drawing.GraphicsUnit]::Pixel)
$bitmapBytes = [System.Collections.Generic.List[byte]]::new()
$descriptors = [System.Collections.Generic.List[string]]::new()
$unicodeOffsets = [System.Collections.Generic.List[string]]::new()
$descriptors.Add('    { .bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0 },')
$first = [int][char]$characters[0]

foreach ($character in $characters) {
    $bitmap = [System.Drawing.Bitmap]::new(28, 28, [System.Drawing.Imaging.PixelFormat]::Format32bppArgb)
    $graphics = [System.Drawing.Graphics]::FromImage($bitmap)
    $graphics.Clear([System.Drawing.Color]::Transparent)
    $graphics.TextRenderingHint = [System.Drawing.Text.TextRenderingHint]::AntiAliasGridFit
    $format = [System.Drawing.StringFormat]::GenericTypographic
    $graphics.DrawString([string]$character, $font, [System.Drawing.Brushes]::White,
        [System.Drawing.PointF]::new(1, -1), $format)
    $index = $bitmapBytes.Count
    for ($y = 0; $y -lt 28; $y++) {
        for ($x = 0; $x -lt 28; $x += 2) {
            $a = [int][math]::Round($bitmap.GetPixel($x, $y).A / 17)
            $b = [int][math]::Round($bitmap.GetPixel(($x + 1), $y).A / 17)
            $bitmapBytes.Add([byte](($a -shl 4) -bor $b))
        }
    }
    $advance = if ([int][char]$character -eq 0x20) { 8 * 16 } elseif ([int][char]$character -lt 128) { 13 * 16 } else { 21 * 16 }
    $descriptors.Add("    { .bitmap_index = $index, .adv_w = $advance, .box_w = 28, .box_h = 28, .ofs_x = 0, .ofs_y = 0 },")
    $unicodeOffsets.Add([string]([int][char]$character - $first))
    $graphics.Dispose()
    $bitmap.Dispose()
}

$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add('#include "lvgl.h"')
$lines.Add('#include "font/lv_font_fmt_txt.h"')
$lines.Add('')
$lines.Add('/* Generated by generate_ui_home_font.ps1; 4 bpp, 20 px Microsoft YaHei subset. */')
$lines.Add('static const uint8_t glyph_bitmap[] = {')
for ($i = 0; $i -lt $bitmapBytes.Count; $i += 16) {
    $end = [math]::Min($i + 15, $bitmapBytes.Count - 1)
    $row = for ($j = $i; $j -le $end; $j++) { '0x{0:x2}' -f $bitmapBytes[$j] }
    $lines.Add('    ' + ($row -join ', ') + ',')
}
$lines.Add('};')
$lines.Add('static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {')
foreach ($descriptor in $descriptors) { $lines.Add($descriptor) }
$lines.Add('};')
$lines.Add('static const uint16_t unicode_list[] = { ' + ($unicodeOffsets -join ', ') + ' };')
$lines.Add('static const lv_font_fmt_txt_cmap_t cmaps[] = {')
$lines.Add("    { .range_start = $first, .range_length = $([int][char]$characters[-1] - $first + 1),")
$lines.Add("      .glyph_id_start = 1, .unicode_list = unicode_list, .glyph_id_ofs_list = NULL,")
$lines.Add("      .list_length = $($characters.Count), .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY },")
$lines.Add('};')
$lines.Add('static const lv_font_fmt_txt_dsc_t font_dsc = {')
$lines.Add('    .glyph_bitmap = glyph_bitmap, .glyph_dsc = glyph_dsc, .cmaps = cmaps,')
$lines.Add('    .cmap_num = 1, .bpp = 4, .bitmap_format = LV_FONT_FMT_TXT_PLAIN,')
$lines.Add('};')
$lines.Add('const lv_font_t ui_home_zh_20 = {')
$lines.Add('    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,')
$lines.Add('    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,')
$lines.Add('    .line_height = 28, .base_line = 0, .subpx = LV_FONT_SUBPX_NONE,')
$lines.Add('    .dsc = &font_dsc, .fallback = &lv_font_montserrat_24,')
$lines.Add('};')
$output = Join-Path $PSScriptRoot 'ui_home_zh_20.c'
[System.IO.File]::WriteAllLines($output, $lines, [System.Text.UTF8Encoding]::new($false))
Write-Output "Generated $output ($($bitmapBytes.Count) bitmap bytes)"
